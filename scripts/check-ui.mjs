import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3000');
await page.locator('.trip-card').first().waitFor();
await page.waitForTimeout(1600);
await page.screenshot({path:'test-results/desktop.png'});
assert.equal(await page.locator('.trip-card').count(),4);
await page.locator('.destination-card').first().click();
assert.equal(await page.locator('.trip-card').count(),1);
await page.locator('.trip-card').first().click();
await page.waitForURL('**/treks/everest-base-camp-cho-la');
await page.getByRole('button',{name:'Talk to the team',exact:true}).click();
assert.equal(await page.locator('dialog').isVisible(),true);
await page.getByLabel('Your name',{exact:true}).fill('Preview Test');
await page.locator('dialog').getByLabel('Email address',{exact:true}).fill('preview@example.com');
await page.getByRole('button',{name:'Send Inquiry',exact:true}).click();
await page.getByRole('alert').filter({hasText:'has not been sent'}).waitFor();
await page.keyboard.press('Escape');
assert.equal(await page.locator('dialog').isVisible(),false);
await page.goto('http://127.0.0.1:3000');
await page.locator('.trip-card').first().waitFor();
assert.equal(await page.locator('.trip-card').count(),4);
await page.getByRole('button',{name:'Tours',exact:true}).click();
await page.getByRole('button',{name:'Explore Journeys',exact:true}).click();
await page.getByText('No journeys match these filters yet.').waitFor();
await page.getByRole('link',{name:'View All Journeys'}).click();
await page.waitForURL('**/treks');
await page.goto('http://127.0.0.1:3000');
await page.locator('#newsletter-email').fill('preview@example.com');
await page.getByRole('button',{name:'Subscribe',exact:true}).click();
await page.getByText('Newsletter signup is not connected yet.',{exact:false}).waitFor();
await page.evaluate(async()=>{for(let y=0;y<document.body.scrollHeight;y+=650){window.scrollTo({top:y,behavior:"instant"});await new Promise(r=>setTimeout(r,70));}window.scrollTo({top:0,behavior:"instant"});});
await page.waitForTimeout(800);
await page.screenshot({path:'test-results/desktop-full.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||i.naturalWidth===0).map(i=>i.src)),[]);
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:3000');
await page.locator('.trip-card').first().waitFor();
await page.getByRole('button',{name:'Menu'}).click();
await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Treks',exact:true}).click();
await page.waitForURL('**/treks');
assert.equal(await page.getByRole('button',{name:'Menu'}).getAttribute('aria-expanded'),'false');
await page.evaluate(async()=>{for(let y=0;y<document.body.scrollHeight;y+=650){window.scrollTo({top:y,behavior:"instant"});await new Promise(r=>setTimeout(r,50));}window.scrollTo({top:0,behavior:"instant"});});
await page.waitForTimeout(800);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'test-results/mobile.png',fullPage:true});
await page.emulateMedia({reducedMotion:'reduce'});
assert.equal(await page.locator('html').evaluate(el=>getComputedStyle(el).scrollBehavior),'auto');
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: desktop/mobile layout, assets, filters, dialogs, inquiry failure, newsletter, reduced motion, no runtime errors.');



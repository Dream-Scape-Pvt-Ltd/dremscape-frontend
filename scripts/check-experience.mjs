import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3000');
await page.locator('.trip-card').first().waitFor();
await page.waitForTimeout(1800);
await page.screenshot({path:'test-results/editorial-hero.png'});
const region=page.getByRole('combobox',{name:/Destination/});
await region.click();
await page.getByRole('listbox').waitFor();
await page.screenshot({path:'test-results/region-picker.png'});
await page.getByRole('option',{name:/Everest & Khumbu/}).click();
assert.match(await region.innerText(),/Everest/);
await region.focus();await page.keyboard.press('ArrowDown');await page.keyboard.press('Home');await page.keyboard.press('Enter');
assert.match(await region.innerText(),/All Himalayan/);
await region.click();await page.keyboard.press('m');await page.keyboard.press('Enter');
assert.match(await region.innerText(),/Manaslu/);
await region.click();await page.keyboard.press('Escape');
assert.equal(await region.getAttribute('aria-expanded'),'false');
await page.getByRole('button',{name:'Explore Journeys',exact:true}).click();
assert.equal(await page.locator('.trip-card').count(),1);
await page.getByRole('button',{name:/Explore Treks/}).click();
const film=page.getByRole('dialog',{name:/Explore Nepal/});await film.waitFor();
await page.getByRole('button',{name:'Pause preview'}).click();
await page.getByRole('button',{name:'Show Annapurna',exact:true}).click();
await page.getByRole('heading',{name:'Find a different rhythm.'}).waitFor();
await page.waitForTimeout(1500);
await page.screenshot({path:'test-results/trek-film.png'});
await page.keyboard.press('Escape');
assert.equal(await film.isVisible(),false);
assert.equal(await page.getByRole('button',{name:/Explore Treks/}).evaluate(el=>el===document.activeElement),true);
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:3000');
await page.waitForTimeout(1700);
await page.screenshot({path:'test-results/editorial-mobile.png'});
await region.click();
const bounds=await page.locator('.journey-options').boundingBox();
assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390&&bounds.y>=0&&bounds.y+bounds.height<=845);
await page.getByRole('option',{name:/Annapurna/}).click();
await page.emulateMedia({reducedMotion:'reduce'});
await page.getByRole('button',{name:/Explore Treks/}).click();
await page.getByRole('button',{name:'Play preview'}).waitFor();
assert.equal(await page.locator('.film-scene.current').evaluate(el=>getComputedStyle(el).animationName),'none');
await page.getByRole('button',{name:'Find My Trek'}).click();
assert.equal(await film.isVisible(),false);
for(const width of [320,390,768,1024,1440]){
  await page.setViewportSize({width,height:900});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`Overflow at ${width}`);
}
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: custom selections, keyboard/typeahead, filtering, film chapters/pause/focus, mobile popup bounds, reduced motion and responsive widths.');

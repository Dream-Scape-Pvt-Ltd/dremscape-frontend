import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3000');
await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Destinations',exact:true}).click();
await page.waitForURL('**/destinations');
await page.locator('.sanctuary-card').first().waitFor();
assert.equal(await page.locator('.sanctuary-card').count(),4);
await page.waitForTimeout(1800);
assert.equal(await page.evaluate(()=>scrollY),0,'Destinations should open at its hero');
await page.screenshot({path:'test-results/destinations-desktop.png'});
await page.getByRole('searchbox',{name:'Search destinations'}).fill('Gokyo');
assert.equal(await page.locator('.sanctuary-card').count(),1);
await page.getByRole('searchbox').fill('not-a-place');
await page.getByText('No regions match just yet.').waitFor();
await page.getByRole('button',{name:'Explore all regions',exact:true}).click();
await page.getByRole('combobox',{name:/Your kind of journey/}).click();
await page.getByRole('option',{name:/The quieter places/}).click();
assert.equal(await page.locator('.sanctuary-card').count(),2);
await page.getByRole('button',{name:'Explore Dolpo',exact:true}).click();
await page.getByRole('heading',{name:'Your trail can start with a conversation.'}).waitFor();
await page.getByRole('button',{name:'Plan a private journey'}).click();
const dialog=page.getByRole('dialog');
assert.match(await dialog.getByRole('textbox',{name:'Your journey'}).inputValue(),/Dolpo/);
await dialog.getByLabel('Your name',{exact:true}).fill('Preview test');
await dialog.getByLabel('Email address',{exact:true}).fill('preview@example.com');
await dialog.getByRole('button',{name:'Send Inquiry'}).click();
await dialog.getByRole('alert').filter({hasText:'has not been sent'}).waitFor();
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Clear filters ×'}).click();
await page.getByRole('button',{name:'Explore Everest',exact:true}).click();
assert.equal(await page.locator('.trip-card').count(),1);
await page.locator('summary').first().click();
assert.equal(await page.locator('details').first().getAttribute('open'),'');
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
await page.screenshot({path:'test-results/destinations-full.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:3000/destinations');
await page.waitForTimeout(1700);
await page.screenshot({path:'test-results/destinations-mobile.png',fullPage:true});
await page.getByRole('button',{name:'Menu'}).click();
await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Home',exact:true}).click();
await page.waitForURL('**/#home');
for(const width of [320,390,768,1024,1440]){
 await page.setViewportSize({width,height:900});
 await page.goto('http://127.0.0.1:3000/destinations');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`Overflow at ${width}`);
}
await page.evaluate(async()=>{for(let y=0;y<document.body.scrollHeight;y+=600){window.scrollTo({top:y,behavior:'instant'});await new Promise(r=>setTimeout(r,70));}});
await page.waitForTimeout(500);
assert.deepEqual(await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||!i.naturalWidth).map(i=>i.src)),[]);
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: Destinations navigation, filters/search/reset, regional treks, inquiry, FAQ, mobile, images and five viewport widths.');
